//! encord-theme: token-based themes + Abaddon/GTK CSS compat.
//!
//! Abaddon styles via GTK CSS selectors (`.messages`, `.message-text`, ...).
//! encord keeps that path working: `res/css/encord.css` is loaded by the
//! native UI verbatim, while `themes/*.toml` provide semantic tokens
//! (colors/radius/spacing/type) that generate matching CSS variables.
//! No DOM, no Chromium — same workflow as BetterDiscord themes, native render.

use std::collections::BTreeMap;
use std::path::Path;
use thiserror::Error;

#[derive(Debug, Error)]
pub enum ThemeError {
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
    #[error("parse: {0}")]
    Parse(String),
}

/// Flat design tokens: `color.bg0`, `radius.md`, ...
#[derive(Clone, Debug, Default)]
pub struct Theme {
    pub id: String,
    pub mode: String,
    pub tokens: BTreeMap<String, String>,
}

impl Theme {
    /// Parse minimal `key = "value"` TOML-ish (no extra dep for M0).
    /// Sections become prefixes: `[color] bg0 = "#..."` -> `color.bg0`.
    pub fn parse_toml(text: &str) -> Result<Self, ThemeError> {
        let mut theme = Theme::default();
        let mut section = String::new();
        for (lineno, raw) in text.lines().enumerate() {
            let line = raw.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if line.starts_with('[') && line.ends_with(']') {
                section = line[1..line.len() - 1].trim().to_string();
                if section == "meta" {
                    continue;
                }
                continue;
            }
            let Some((k, v)) = line.split_once('=') else {
                return Err(ThemeError::Parse(format!(
                    "line {}: expected k = v",
                    lineno + 1
                )));
            };
            let key = k.trim().to_string();
            let raw_val = v.trim();
            // Quoted values are literal (so "#000" survives `#`-comment stripping).
            let val = if let Some(stripped) = raw_val
                .strip_prefix('"')
                .and_then(|s| s.split_once('"'))
                .map(|(head, _)| head.to_string())
                .or_else(|| {
                    raw_val
                        .strip_prefix('\'')
                        .and_then(|s| s.split_once('\''))
                        .map(|(head, _)| head.to_string())
                }) {
                stripped
            } else {
                let head = raw_val.split_once('#').map(|(h, _)| h).unwrap_or(raw_val);
                head.trim().to_string()
            };
            if section == "meta" {
                if key == "id" {
                    theme.id = val;
                } else if key == "mode" {
                    theme.mode = val;
                }
                continue;
            }
            let full = if section.is_empty() {
                key
            } else {
                format!("{section}.{key}")
            };
            theme.tokens.insert(full, val);
        }
        if theme.mode.is_empty() {
            theme.mode = "dark".to_string();
        }
        Ok(theme)
    }

    pub fn load_toml(path: &Path) -> Result<Self, ThemeError> {
        let text = std::fs::read_to_string(path)?;
        Self::parse_toml(&text)
    }

    pub fn get(&self, token: &str) -> Option<&str> {
        self.tokens.get(token).map(String::as_str)
    }

    /// Emit GTK-CSS `:root` variables + Abaddon selector defaults so a
    /// single theme file drives both token UI and legacy CSS selectors.
    pub fn to_gtk_css(&self) -> String {
        let mut out = String::from("/* generated by encord-theme — do not edit */\n:root {\n");
        for (k, v) in &self.tokens {
            let var = k.replace('.', "-");
            out.push_str(&format!("  --encord-{var}: {v};\n"));
        }
        out.push_str("}\n");
        out.push_str(
            ".messages { background-color: var(--encord-color-bg0); }\n\
             .message-text { color: var(--encord-color-text0); }\n\
             .channel-list { background-color: var(--encord-color-bg1); }\n",
        );
        out
    }
}

/// Validate that a user CSS file only touches the known Abaddon selector
/// allowlist (defense against typos; CSS itself is inert — no JS).
pub fn validate_css_selectors(css: &str) -> Vec<String> {
    const KNOWN: &[&str] = &[
        ".app-window",
        ".channel-list",
        ".messages",
        ".message-container",
        ".message-container-author",
        ".message-text",
        ".message-input",
        ".embed",
        ".member-list",
        ".typing-indicator",
        ".reaction-box",
        ":root",
    ];
    let mut unknown = Vec::new();
    for raw in css.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with("/*") || line.starts_with("//") {
            continue;
        }
        if line.starts_with('.') || line.starts_with(':') || line.starts_with('#') {
            let sel = line
                .split([' ', '{', ','])
                .next()
                .unwrap_or("")
                .trim()
                .to_string();
            // Allow pseudo variants (`.messages:hover`) and compound
            // classes (`.message-text.pending`, `.reaction-box.reacted`)
            // by matching the leading known selector.
            let base = sel.split(':').next().unwrap_or(&sel);
            let head = base
                .split('.')
                .nth(1)
                .map(|s| format!(".{s}"))
                .unwrap_or_default();
            // For `.a.b`, also accept when `.a` is known.
            let stem = if head.is_empty() {
                base.to_string()
            } else {
                // `split('.')` on ".message-text.pending" yields
                // ["", "message-text", "pending"]; rebuild ".message-text".
                head
            };
            let ok = KNOWN
                .iter()
                .any(|k| *k == base || *k == stem || (*k == ":root" && sel.starts_with(":root")));
            if !ok && !sel.is_empty() {
                unknown.push(sel);
            }
        }
    }
    unknown
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_theme_toml() {
        let t =
            Theme::parse_toml("[meta]\nid=\"x\"\nmode=\"dark\"\n[color]\nbg0=\"#000\"\n").unwrap();
        assert_eq!(t.id, "x");
        assert_eq!(t.get("color.bg0"), Some("#000"));
        let css = t.to_gtk_css();
        assert!(css.contains("--encord-color-bg0"));
        assert!(css.contains(".message-text"));
    }

    #[test]
    fn flags_unknown_selectors() {
        let bad = ".messages { }\n.fake-selector-xyz { }";
        let u = validate_css_selectors(bad);
        assert_eq!(u, vec![".fake-selector-xyz".to_string()]);
    }

    #[test]
    fn allows_compound_and_shipped_css_selectors() {
        // Compound classes + pseudo variants share the known base.
        let ok = ".message-text.pending { }\n.message-text.failed { }\n\
                  .reaction-box.reacted { }\n.messages:hover { }\n\
                  .message-container-author { }";
        assert!(validate_css_selectors(ok).is_empty());
    }
}
